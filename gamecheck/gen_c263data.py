"""Generate c263data.h (constants of the Minecraft 26.3 overworld climate) from game dumps made with Probe.java.

    python3 gamecheck/gen_c263data.py <probe_spline.txt> <probe_noise.txt> > c263data.h

- spline: the overworld/offset cubic spline (coordinates continents / erosion / ridges_folded), exact float bits;
- per climate noise: the octave indices (base_octave + i for every non-zero amplitude modifier, from the noise JSON,
  checked against the frequencies in the dump), the float amplitude of each layer (seed independent, checked), and
  the md5 halves of the strings the game hashes ("minecraft:<noise>" and "octave_<k>").
"""
import hashlib, struct, sys

NOISES = ["temperature", "vegetation", "continentalness", "erosion", "ridge", "offset"]
COORDS = {"minecraft:overworld/continents": 0, "minecraft:overworld/erosion": 1, "minecraft:overworld/ridges_folded": 2,
          "minecraft:overworld/ridges": 3}


def md5pair(s):
    d = hashlib.md5(s.encode("utf-8")).digest()
    return struct.unpack(">QQ", d)


def parse_spline(lines):
    nodes, consts = [], []          # node: (coord, [(loc, der, kind, idx)])
    pos = [0]

    def parse():
        l = lines[pos[0]].strip(); pos[0] += 1
        if l.startswith("C "):
            consts.append(l.split()[1]); return ("C", len(consts) - 1)
        _, coord, n = l.split()
        me = len(nodes); nodes.append(None)
        pts = []
        for _ in range(int(n)):
            p = lines[pos[0]].strip().split(); pos[0] += 1
            assert p[0] == "P"
            kind, idx = parse()
            pts.append((p[1], p[2], kind, idx))
        nodes[me] = (COORDS[coord], pts)
        return ("M", me)

    root = parse()
    assert root == ("M", 0) and pos[0] == len(lines)
    return nodes, consts


def main():
    sl = [l for l in open(sys.argv[1]) if l.strip()]
    nodes, consts = parse_spline(sl)
    layers = {}
    for l in open(sys.argv[2]):
        if l.startswith("L "):
            f = l.split()
            layers.setdefault(f[1], []).append((int(f[2]), f[4], f[6]))   # index, freq bits, amp bits
    out = ["// Generated by gamecheck/gen_c263data.py from the Minecraft 26.3 server jar (Probe.java dumps). Do not edit.",
           "#ifndef C263DATA_H_", "#define C263DATA_H_", "#include <stdint.h>", ""]
    # spline as flat arrays: node i has n points starting at pt_start[i]; a point value is a constant (kind 0) or node (kind 1)
    npts = sum(len(p) for _, p in nodes)
    out.append(f"#define C263_SPLINE_NODES {len(nodes)}")
    out.append(f"#define C263_SPLINE_POINTS {npts}")
    out.append(f"#define C263_SPLINE_CONSTS {len(consts)}")
    out.append("static const uint8_t C263_SP_COORD[C263_SPLINE_NODES] = {" + ",".join(str(c) for c, _ in nodes) + "};")
    starts, s = [], 0
    for _, p in nodes:
        starts.append(s); s += len(p)
    out.append("static const uint16_t C263_SP_START[C263_SPLINE_NODES] = {" + ",".join(map(str, starts)) + "};")
    out.append("static const uint8_t C263_SP_LEN[C263_SPLINE_NODES] = {" + ",".join(str(len(p)) for _, p in nodes) + "};")
    locs, ders, kinds, idxs = [], [], [], []
    for _, p in nodes:
        for loc, der, kind, idx in p:
            locs.append("0x" + loc); ders.append("0x" + der); kinds.append("1" if kind == "M" else "0"); idxs.append(str(idx))
    out.append("static const uint32_t C263_SP_LOC[C263_SPLINE_POINTS] = {" + ",".join(locs) + "};")
    out.append("static const uint32_t C263_SP_DER[C263_SPLINE_POINTS] = {" + ",".join(ders) + "};")
    out.append("static const uint8_t C263_SP_KIND[C263_SPLINE_POINTS] = {" + ",".join(kinds) + "};")
    out.append("static const uint16_t C263_SP_IDX[C263_SPLINE_POINTS] = {" + ",".join(idxs) + "};")
    out.append("static const uint32_t C263_SP_CONST[C263_SPLINE_CONSTS] = {" + ",".join("0x" + c for c in consts) + "};")
    out.append("")
    # noises
    base = {"temperature": (-10, [1.5, 0, 1, 0, 0, 0]), "vegetation": (-8, [1, 1, 0, 0, 0, 0]),
            "continentalness": (-9, [1, 1, 2, 2, 2, 1, 1, 1, 1]), "erosion": (-9, [1, 1, 0, 1, 1]),
            "ridge": (-7, [1, 2, 1, 0, 0, 0]), "offset": (-3, [1, 1, 1, 0])}
    out.append("#define C263_MAX_OCT 9")
    for k, n in enumerate(NOISES):
        b, mods = base[n]
        octs = [b + i for i, m in enumerate(mods) if m != 0]
        L = layers[n]
        assert len(L) == 2 * len(octs), n
        for j, o in enumerate(octs):                           # check frequencies: A = 2^o, B = 2^o * 1.0181268882175227
            fa = struct.unpack(">d", bytes.fromhex(L[2 * j][1]))[0]; fb = struct.unpack(">d", bytes.fromhex(L[2 * j + 1][1]))[0]
            assert fa == 2.0 ** o and fb == (2.0 ** o) * 1.0181268882175227, (n, o, fa, fb)
            assert L[2 * j][2] == L[2 * j + 1][2], (n, o)
        hi, lo = md5pair("minecraft:" + n)
        out.append(f"// {n}: octaves {octs}")
        out.append(f"#define C263_N{k}_COUNT {len(octs)}")
        out.append(f"static const int C263_N{k}_OCT[] = {{{','.join(map(str, octs))}}};")
        out.append(f"static const uint32_t C263_N{k}_AMP[] = {{{','.join('0x' + L[2 * j][2] for j in range(len(octs)))}}};")
        out.append(f"static const uint64_t C263_N{k}_MD5[2] = {{0x{hi:016x}ULL, 0x{lo:016x}ULL}};")
        oc = []
        for o in octs:
            h2, l2 = md5pair(f"octave_{o}")
            oc.append(f"0x{h2:016x}ULL,0x{l2:016x}ULL")
        out.append(f"static const uint64_t C263_N{k}_OCTMD5[][2] = {{{','.join('{' + x + '}' for x in oc)}}};")
    out.append("")
    # NoiseSpawnFinder: every (angle, radius) of the two radial passes is seed independent, so the integer offsets
    # (int)(Math.sin(angle) * radius), (int)(Math.cos(angle) * radius) are a fixed table (from SinCos.java, the game's JVM).
    # This avoids depending on libm: glibc and Java differ in the last bit for a few of these angles, never in the offset.
    if len(sys.argv) > 3:
        rows = [l.split() for l in open(sys.argv[3]) if l.strip()]
        passes, prev = [[]], None
        for r in rows:
            rad = struct.unpack(">f", struct.pack(">I", int(r[1])))[0]
            if prev is not None and rad < prev:
                passes.append([])
            passes[-1].append((int(r[4]), int(r[5])))
            prev = rad
        assert len(passes) == 2
        out.append(f"#define C263_SPAWN_P1 {len(passes[0])}   // radialSearch(2048, 512)")
        out.append(f"#define C263_SPAWN_P2 {len(passes[1])}   // radialSearch(512, 32)")
        allp = passes[0] + passes[1]
        out.append("static const int16_t C263_SPAWN_DX[] = {" + ",".join(str(a) for a, _ in allp) + "};")
        out.append("static const int16_t C263_SPAWN_DZ[] = {" + ",".join(str(b) for _, b in allp) + "};")
        out.append("")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
